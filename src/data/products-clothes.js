const noBeauty = { ingredients: [], concerns: [], warranty: "" };

const sizes = (stocks) => ({
  label: "Size",
  display: "text",
  options: Object.entries(stocks).map(([name, stock]) => ({ id: name.toLowerCase().replace(/[^a-z0-9]+/g, "-"), name, stock })),
});
const total = (stocks) => Object.values(stocks).reduce((sum, value) => sum + value, 0);

function garment({ sizeStock, ...product }) {
  return { ...noBeauty, ...product, variants: sizes(sizeStock), stock: total(sizeStock) };
}

